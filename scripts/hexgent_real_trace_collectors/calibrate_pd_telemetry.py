#!/usr/bin/env python3
"""Calibrate PD profile and transfer assumptions from SGLang request telemetry.

The input is one or more worker logs containing ``Req Time Stats`` lines. The
output is a compact JSON calibration artifact suitable for selecting the
planner transfer-bandwidth override and checking queue/compute behavior.
"""

from __future__ import annotations

import argparse
import json
import math
import re
from pathlib import Path
from statistics import mean, median
from typing import Dict, Iterable, List, Mapping, Optional, Tuple


_STATS_RE = re.compile(
    r"Req Time Stats\(rid=(?P<rid>[^,]+).*?"
    r"input len=(?P<input>\d+), output len=(?P<output>\d+), "
    r"type=(?P<stage>\w+)\):.*?"
    r"(?:(?:bootstrap|prealloc)_queue_duration\((?P<admission>[\d.]+)ms\).*?; )?"
    r"(?:transfer_duration=(?P<transfer>[\d.]+)ms; )?"
    r"(?:queue_duration=(?P<queue>[\d.]+)ms, )?"
    r"forward_duration=(?P<forward>[\d.]+)ms"
)

_STATS_V0515_HEADER_RE = re.compile(
    r"ReqTimeStats\(rid=(?P<rid>[^,]+)"
    r"(?:, bootstrap_room=(?P<bootstrap_room>[^,]+))?, "
    r"input_len=(?P<input>\d+), cached_input_len=(?P<cached_input>\d+), "
    r"output_len=(?P<output>\d+), type=(?P<stage>\w+)\):(?P<details>.*)"
)


def _v0515_detail(details: str, name: str, unit: str = "ms") -> Optional[float]:
    match = re.search(rf"(?:^|, ){re.escape(name)}=([\d.]+){re.escape(unit)}", details)
    return float(match.group(1)) if match is not None else None


def kv_bytes_per_token_from_config(
    model_config: Mapping[str, object], *, kv_dtype_bytes: float = 2.0
) -> int:
    """Return the KV-cache bytes generated by one input token.

    The cache stores K and V for every transformer layer.  ``head_dim`` is
    optional in Hugging Face configs and can be derived from the hidden size
    when the attention head count is available.
    """

    try:
        layers = int(model_config["num_hidden_layers"])
        hidden_size = int(model_config["hidden_size"])
        attention_heads = int(model_config["num_attention_heads"])
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            "model config must define num_hidden_layers, hidden_size, and "
            "num_attention_heads"
        ) from exc

    kv_heads = int(model_config.get("num_key_value_heads", attention_heads))
    head_dim = int(model_config.get("head_dim") or (hidden_size // attention_heads))
    if layers <= 0 or kv_heads <= 0 or head_dim <= 0 or kv_dtype_bytes <= 0:
        raise ValueError("model config KV dimensions and dtype bytes must be positive")

    # K and V are both stored.  This is independent of the request's output
    # length and is therefore the right multiplier for prefill->decode KV IO.
    return int(round(layers * 2 * kv_heads * head_dim * kv_dtype_bytes))


def resolve_bytes_per_input_token(
    *,
    explicit_bytes: Optional[int],
    model_config: Optional[Mapping[str, object]],
    kv_dtype_bytes: float,
) -> Tuple[int, str]:
    """Resolve KV bytes/token with explicit and config-driven precedence."""

    if explicit_bytes is not None:
        if explicit_bytes <= 0:
            raise ValueError("--bytes-per-input-token must be positive")
        return explicit_bytes, "explicit"
    if model_config is not None:
        return (
            kv_bytes_per_token_from_config(
                model_config, kv_dtype_bytes=kv_dtype_bytes
            ),
            "model_config",
        )
    # Preserve the historical CLI behavior for callers that have not supplied
    # a model config yet. New measurements should pass --model-config.
    return 131072, "legacy_default"


def _percentile(values: List[float], fraction: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, math.ceil(fraction * len(ordered)) - 1))
    return float(ordered[index])


def _summary(values: Iterable[float]) -> Dict[str, float]:
    values = [float(value) for value in values]
    if not values:
        return {"count": 0, "mean": 0.0, "median": 0.0, "p95": 0.0, "p99": 0.0}
    return {
        "count": len(values),
        "mean": mean(values),
        "median": median(values),
        "p95": _percentile(values, 0.95),
        "p99": _percentile(values, 0.99),
    }


def read_rows(
    log_paths: Iterable[Path],
    *,
    bytes_per_input_token: int,
    min_input_tokens: int = 1,
) -> List[dict]:
    rows: List[dict] = []
    for path in log_paths:
        for line in path.read_text(errors="ignore").splitlines():
            match = _STATS_RE.search(line)
            if match is not None:
                row = match.groupdict()
                row["prefill_transfer_observed_ms"] = None
                row["prefill_transfer_observed_bandwidth_bytes_per_s"] = None
                row["transfer_total_bytes"] = None
            else:
                match = _STATS_V0515_HEADER_RE.search(line)
                if match is None:
                    continue
                row = match.groupdict()
                details = row.pop("details").strip()
                row["admission"] = None
                row["transfer"] = _v0515_detail(details, "transfer_duration")
                row["queue"] = _v0515_detail(details, "queue_duration")
                row["forward"] = _v0515_detail(details, "forward_duration")
                transfer_speed_gb_s = _v0515_detail(
                    details, "transfer_speed", " GB/s"
                )
                transfer_total_mb = _v0515_detail(
                    details, "transfer_total", " MB"
                )
                if transfer_speed_gb_s and transfer_total_mb is not None:
                    row["prefill_transfer_observed_ms"] = (
                        transfer_total_mb / 1024 / transfer_speed_gb_s * 1000
                    )
                    row["prefill_transfer_observed_bandwidth_bytes_per_s"] = (
                        transfer_speed_gb_s * 1024**3
                    )
                    row["transfer_total_bytes"] = transfer_total_mb * 1024**2
                else:
                    row["prefill_transfer_observed_ms"] = None
                    row["prefill_transfer_observed_bandwidth_bytes_per_s"] = None
                    row["transfer_total_bytes"] = None
            if row["rid"].startswith("HEALTH_CHECK"):
                continue
            row["input_tokens"] = int(row.pop("input"))
            row["output_tokens"] = int(row.pop("output"))
            if row["input_tokens"] < min_input_tokens:
                continue
            row["bytes"] = row["input_tokens"] * bytes_per_input_token
            for key in ("transfer", "queue", "forward"):
                row[f"{key}_ms"] = (
                    float(row.pop(key)) if row.get(key) is not None else None
                )
            row["admission_queue_ms"] = (
                float(row.pop("admission"))
                if row.get("admission") is not None
                else None
            )
            if row["transfer_ms"] and row["bytes"] > 0:
                row["effective_bandwidth_bytes_per_s"] = row["bytes"] / (
                    row["transfer_ms"] / 1000.0
                )
            rows.append(row)
    return rows


def build_calibration(
    rows: List[dict],
    *,
    bytes_per_input_token: int,
    bytes_source: str = "explicit",
    model: str = "",
    worker_class: str = "default",
    max_inflight_transfers: int = 0,
) -> dict:
    if max_inflight_transfers < 0:
        raise ValueError("max_inflight_transfers must be non-negative")
    result = {
        "schema_version": 1,
        "bytes_per_input_token": bytes_per_input_token,
        "bytes_per_input_token_source": bytes_source,
        "rows": len(rows),
        "stages": {},
        "profiles": [],
    }
    for stage in ("prefill", "decode"):
        stage_rows = [row for row in rows if row["stage"] == stage]
        result["stages"][stage] = {
            "rows": len(stage_rows),
            "queue_ms": _summary(
                row.get("queue_ms")
                for row in stage_rows
                if row.get("queue_ms") is not None
            ),
            "admission_queue_ms": _summary(
                row.get("admission_queue_ms")
                for row in stage_rows
                if row.get("admission_queue_ms") is not None
            ),
            "forward_ms": _summary(
                row.get("forward_ms")
                for row in stage_rows
                if row.get("forward_ms") is not None
            ),
        }

    grouped: Dict[Tuple[int, int], Dict[str, List[float]]] = {}
    for row in rows:
        key = (int(row["input_tokens"]), int(row["output_tokens"]))
        bucket = grouped.setdefault(
            key,
            {"prefill": [], "decode": [], "transfer": []},
        )
        stage = str(row.get("stage", ""))
        forward_ms = row.get("forward_ms")
        if stage in {"prefill", "decode"} and forward_ms is not None:
            bucket[stage].append(float(forward_ms))
        transfer_ms = row.get("transfer_ms")
        if stage == "decode" and transfer_ms is not None:
            bucket["transfer"].append(float(transfer_ms))
    for (input_tokens, output_tokens), bucket in sorted(grouped.items()):
        if not bucket["prefill"] and not bucket["decode"]:
            continue
        result["profiles"].append(
            {
                "model": model,
                "worker_class": worker_class,
                "input_len": input_tokens,
                "output_len": output_tokens,
                "estimated_prefill_time": (
                    median(bucket["prefill"]) if bucket["prefill"] else 0.0
                ),
                "estimated_decode_time": (
                    median(bucket["decode"]) if bucket["decode"] else 0.0
                ),
                "estimated_transfer_time": (
                    median(bucket["transfer"]) if bucket["transfer"] else 0.0
                ),
            }
        )

    decode_rows = [row for row in rows if row["stage"] == "decode"]
    transfer_ms = [
        row["transfer_ms"] for row in decode_rows if row["transfer_ms"] is not None
    ]
    bandwidth = [
        row["effective_bandwidth_bytes_per_s"]
        for row in decode_rows
        if row.get("effective_bandwidth_bytes_per_s")
    ]
    result["transfer"] = {
        "rows": len(transfer_ms),
        # This is part of the calibration contract. A bandwidth measured with
        # cap=2 must not later be interpreted as an uncapped link or as cap=1.
        "max_inflight_transfers": int(max_inflight_transfers),
        "duration_ms": _summary(transfer_ms),
        "effective_bandwidth_bytes_per_s": _summary(bandwidth),
        # Median is robust to the occasional TCP stall and is the planner's
        # default calibration target. Use p10 for a conservative SLA model.
        "recommended_bandwidth_bytes_per_s": median(bandwidth) if bandwidth else 0.0,
        "conservative_bandwidth_bytes_per_s": _percentile(bandwidth, 0.10),
    }
    prefill_transfer_rows = [
        row for row in rows if row.get("prefill_transfer_observed_ms") is not None
    ]
    result["prefill_transfer_observation"] = {
        # Mooncake leaves KVTransferMetric.transfer_latency_s unset. SGLang
        # therefore derives this value from prefill_transfer_queue_entry_time
        # to completion_time and documents it as the last-chunk boundary. It
        # is not a CUDA-event measurement of pure DMA copy time.
        "boundary": "prefill_transfer_queue_to_completion_last_chunk",
        "rows": len(prefill_transfer_rows),
        "duration_ms": _summary(
            row["prefill_transfer_observed_ms"] for row in prefill_transfer_rows
        ),
        "bandwidth_bytes_per_s": _summary(
            row["prefill_transfer_observed_bandwidth_bytes_per_s"]
            for row in prefill_transfer_rows
        ),
        "payload_bytes": _summary(
            row["transfer_total_bytes"] for row in prefill_transfer_rows
        ),
    }
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--log-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--bytes-per-input-token",
        type=int,
        default=None,
        help="Explicit KV bytes per input token; overrides --model-config.",
    )
    parser.add_argument(
        "--model-config",
        type=Path,
        help="Hugging Face config.json used to derive KV bytes per token.",
    )
    parser.add_argument(
        "--kv-dtype-bytes",
        type=float,
        default=2.0,
        help="Bytes per KV element; 2 for BF16/FP16, 1 for FP8.",
    )
    parser.add_argument("--model", default="")
    parser.add_argument("--worker-class", default="default")
    parser.add_argument(
        "--max-inflight-transfers",
        type=int,
        default=0,
        help="Transfer concurrency used while collecting the telemetry; 0 means uncapped.",
    )
    parser.add_argument(
        "--min-input-tokens",
        type=int,
        default=1,
        help="Ignore warmup/probe rows shorter than this input length.",
    )
    args = parser.parse_args()

    model_config = None
    if args.model_config is not None:
        config_path = args.model_config
        if config_path.is_dir():
            config_path = config_path / "config.json"
        model_config = json.loads(config_path.read_text())
    bytes_per_input_token, bytes_source = resolve_bytes_per_input_token(
        explicit_bytes=args.bytes_per_input_token,
        model_config=model_config,
        kv_dtype_bytes=args.kv_dtype_bytes,
    )
    paths = sorted(args.log_dir.glob("*.log"))
    rows = read_rows(
        paths,
        bytes_per_input_token=bytes_per_input_token,
        min_input_tokens=max(1, args.min_input_tokens),
    )
    calibration = build_calibration(
        rows,
        bytes_per_input_token=bytes_per_input_token,
        bytes_source=bytes_source,
        model=args.model,
        worker_class=args.worker_class,
        max_inflight_transfers=max(0, args.max_inflight_transfers),
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(calibration, indent=2) + "\n")
    print(json.dumps(calibration, indent=2))


if __name__ == "__main__":
    main()
